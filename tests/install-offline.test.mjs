import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash, generateKeyPairSync } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import JSZip from '../src/import/vendor/jszip.min.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const windows = { skip: process.platform !== 'win32' };
const pem = () => generateKeyPairSync('ed25519').publicKey.export({ type: 'spki', format: 'pem' });
const publicKeyPem = pem();
function fixture(t) {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'offline-install-'));
  t.after(() => fs.rmSync(temp, { recursive: true, force: true }));
  const install = path.join(temp, 'local install');
  const extension = path.join(install, 'extension');
  let count = 0;
  return { temp, install, extension, async pack(options = {}) {
    const zip = new JSZip();
    zip.file('manifest.json', JSON.stringify({ manifest_version: 3, name: 'Synthetic offline test',
      version: options.version ?? '1.0.0', background: { service_worker: 'src/license/guard-worker.mjs', type: 'module' },
      ...(options.manifest ?? {}) }));
    zip.file('src/license/guard-worker.mjs', "import { paidConfig } from './paid-config.mjs';\n");
    zip.file('src/license/paid-config.mjs', `// Generated by scripts/build-paid.ps1\nexport const paidConfig = {\n` +
      `  buildFlavor: 'paid',\n  verificationMode: '${options.mode ?? 'offline'}',\n` +
      `  licenseServiceUrl: null,\n  publicWebsite: null,\n  publicKeyPem: ${JSON.stringify(options.publicKeyPem ?? publicKeyPem)},\n` +
      `  requireSignedEntitlement: true,\n};\n`);
    for (const [name, content] of Object.entries(options.files ?? {})) zip.file(name, content);
    const bytes = await zip.generateAsync({ type: 'nodebuffer' });
    const zipPath = path.join(temp, `package ${++count}.zip`);
    const checksumPath = path.join(temp, `sums ${count}.txt`);
    fs.writeFileSync(zipPath, bytes);
    fs.writeFileSync(checksumPath, `${createHash('sha256').update(bytes).digest('hex')}  ${path.basename(zipPath)}\n`);
    return { zipPath, checksumPath };
  }, run(pack, ...flags) {
    return spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
      '-File', path.join(root, 'scripts/install-offline.ps1'), '-ZipPath', pack.zipPath,
      '-ChecksumPath', pack.checksumPath, '-InstallRoot', install, ...flags],
    { cwd: root, encoding: 'utf8', timeout: 30000 });
  } };
}
const success = (result) => assert.equal(result.status, 0, result.stdout + result.stderr);
const failure = (result) => assert.notEqual(result.status, 0, result.stdout + result.stderr);

test('local install and full update keep one load path and archive the prior tree', windows, async (t) => {
  const f = fixture(t);
  const first = await f.pack({ files: { 'obsolete.txt': 'old release' } });
  success(f.run(first));
  assert.equal(JSON.parse(fs.readFileSync(path.join(f.extension, 'manifest.json'))).version, '1.0.0');
  failure(f.run(first));
  assert.equal(fs.readFileSync(path.join(f.extension, 'obsolete.txt'), 'utf8'), 'old release');
  const second = await f.pack({ version: '1.1.0', files: { 'new.txt': 'new release' } });
  success(f.run(second, '-Update'));
  assert.equal(JSON.parse(fs.readFileSync(path.join(f.extension, 'manifest.json'))).version, '1.1.0');
  assert.equal(fs.existsSync(path.join(f.extension, 'obsolete.txt')), false);
  assert.equal(fs.readFileSync(path.join(f.extension, 'new.txt'), 'utf8'), 'new release');
  const backups = fs.readdirSync(f.install).filter((name) => name.startsWith('backup-'));
  assert.equal(backups.length, 1);
  assert.equal(fs.readFileSync(path.join(f.install, backups[0], 'obsolete.txt'), 'utf8'), 'old release');
});

test('bad hashes, unsafe paths and remote update metadata cannot replace the installed tree', windows, async (t) => {
  const f = fixture(t);
  success(f.run(await f.pack({ files: { 'keep.txt': 'installed' } })));
  const badHash = await f.pack();
  fs.writeFileSync(badHash.checksumPath, `${'0'.repeat(64)}  ${path.basename(badHash.zipPath)}\n`);
  const badPackages = [badHash,
    await f.pack({ files: { '../escaped.txt': 'escape' } }),
    await f.pack({ files: { 'src/../../escaped.txt': 'escape' } }),
    await f.pack({ manifest: { update_url: 'https://unused.invalid/update.xml' } }),
    await f.pack({ mode: 'online' }),
    await f.pack({ publicKeyPem: pem() }),
    await f.pack({ manifest: { key: 'different-browser-identity' } }),
  ];
  for (const pack of badPackages) {
    failure(f.run(pack, '-Update'));
    assert.equal(fs.readFileSync(path.join(f.extension, 'keep.txt'), 'utf8'), 'installed');
    assert.equal(JSON.parse(fs.readFileSync(path.join(f.extension, 'manifest.json'))).version, '1.0.0');
  }
  assert.equal(fs.existsSync(path.join(f.temp, 'escaped.txt')), false);
  assert.equal(fs.existsSync(path.join(f.install, 'escaped.txt')), false);
});

test('update requires an existing installation', windows, async (t) => {
  const f = fixture(t);
  failure(f.run(await f.pack(), '-Update'));
  assert.equal(fs.existsSync(f.extension), false);
});

test('fresh offline paid build installs, updates and activates an issued seat code', windows, async (t) => {
  const f = fixture(t);
  const publicPath = path.join(f.temp, 'public.pem');
  const privatePath = path.join(f.temp, 'operator-private.pem');
  const keys = generateKeyPairSync('ed25519');
  fs.writeFileSync(publicPath, keys.publicKey.export({ type: 'spki', format: 'pem' }));
  fs.writeFileSync(privatePath, keys.privateKey.export({ type: 'pkcs8', format: 'pem' }));
  const result = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
    '-File', path.join(root, 'scripts/build-paid.ps1'), '-Offline', '-PublicKeyPemPath', publicPath],
  { cwd: root, encoding: 'utf8', timeout: 60000 });
  success(result);
  const match = result.stdout.match(/ZIP[^\r\n]*?([A-Za-z]:\\[^\r\n]+\.zip)/);
  assert.ok(match, result.stdout);
  const zipPath = match[1];
  assert.ok(path.resolve(zipPath).startsWith(path.join(root, 'dist') + path.sep));
  const pack = { zipPath, checksumPath: path.join(path.dirname(zipPath), 'SHA256SUMS.txt') };
  success(f.run(pack));
  success(f.run(pack, '-Update'));
  const manifest = JSON.parse(fs.readFileSync(path.join(f.extension, 'manifest.json')));
  assert.equal(manifest.background.service_worker, 'src/license/guard-worker.mjs');
  assert.equal(manifest.update_url, undefined);

  // Exercise the delivered modules after installation/update, using an actual CLI code.
  const installId = '11111111-2222-4333-a444-555555555555';
  const issued = spawnSync(process.execPath, [path.join(root, 'scripts/issue-entitlement.mjs'),
    '--private-key', privatePath, '--install-id', installId, '--license-id', 'seat-installed-001',
    '--days', '1', '--code-only'], { cwd: root, encoding: 'utf8', timeout: 10000 });
  success(issued);
  const packed = (name) => import(pathToFileURL(path.join(f.extension, 'src/license', name)));
  const { paidConfig } = await packed('paid-config.mjs');
  const { activateLocalToken, readLicenseStatus } = await packed('entitlement.mjs');
  const { createLicenseClient } = await packed('client.mjs');
  const data = { resumeLicenseInstallId: installId };
  const storage = {
    async get(key) { return { [key]: data[key] }; },
    async set(value) { Object.assign(data, structuredClone(value)); },
  };
  assert.equal((await activateLocalToken({ storage, tokenText: issued.stdout, config: paidConfig })).allowed, true);
  const status = await readLicenseStatus({ flavor: 'paid', storage, config: paidConfig });
  assert.equal(status.allowed, true);
  assert.equal(status.licenseId, 'seat-installed-001');
  let fetchCalls = 0;
  const client = createLicenseClient({ config: paidConfig, storage, fetchImpl: async () => {
    fetchCalls += 1;
    throw new Error('network forbidden');
  } });
  assert.equal(await client.verifyBeforeFill(), true);
  assert.equal(fetchCalls, 0);
});
